def send_smtp_email(
    smtp_config: Dict[str, Any],
    recipients: List[str],
    subject: str,
    text_body: str,
    html_body: Optional[str] = None,
    timeout: float = 12.0
) -> Tuple[bool, str]:
    """
    Synchronously transmits an email message via SMTP.
    Returns (True, 'Success message') or (False, 'Detailed error reason').
    """
    host = str(smtp_config.get("smtp_host", "")).strip()
    port = int(smtp_config.get("smtp_port", 587) or 587)
    user = str(smtp_config.get("smtp_user", "")).strip()
    password = str(smtp_config.get("smtp_password", ""))
    security = str(smtp_config.get("smtp_security", "STARTTLS")).strip().upper()
    sender = str(smtp_config.get("smtp_sender", "")).strip() or user or "ServerMon Alert <noreply@servermon.local>"

    if not host:
        return False, "SMTP Host address cannot be empty."

    clean_recipients = parse_recipients(recipients)
    if not clean_recipients:
        return False, "No valid recipient email addresses specified."

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = ", ".join(clean_recipients)
    msg["Date"] = email.utils.formatdate(localtime=True)
    msg.set_content(text_body)
    if html_body:
        msg.add_alternative(html_body, subtype="html")

    server = None
    try:
        if "SSL" in security:
            context = ssl.create_default_context()
            server = smtplib.SMTP_SSL(host, port, timeout=timeout, context=context)
        else:
            server = smtplib.SMTP(host, port, timeout=timeout)
            if "STARTTLS" in security or security == "TLS":
                context = ssl.create_default_context()
                server.starttls(context=context)

        if user and password:
            server.login(user, password)

        envelope_from = email.utils.parseaddr(sender)[1] or sender
        server.send_message(msg, from_addr=envelope_from, to_addrs=clean_recipients)
        try:
            server.quit()
        except Exception:
            pass

        return True, f"Successfully dispatched email to {len(clean_recipients)} recipient(s)."

    except ssl.SSLCertVerificationError as e:
        return False, f"SSL Certificate verification failed for {host}:{port}: {e}"
    except smtplib.SMTPAuthenticationError as e:
        return False, f"SMTP Authentication failed (check username / app password): {e}"
    except smtplib.SMTPConnectError as e:
        return False, f"Could not connect to SMTP server {host}:{port}: {e}"
    except smtplib.SMTPServerDisconnected:
        return False, "SMTP server unexpectedly closed the connection."
    except TimeoutError:
        return False, f"Connection to {host}:{port} timed out after {timeout}s."
    except OSError as e:
        return False, f"Network socket error connecting to {host}:{port}: {e}"
    except Exception as e:
        return False, f"SMTP delivery failed: {e}"
    finally:
        if server is not None:
            try:
                server.close()
            except Exception:
                pass


class EmailWorker(QThread):
    """Asynchronous background worker thread for non-blocking SMTP email dispatch."""

    finished_signal = Signal(bool, str)

    def __init__(
        self,
        smtp_config: Dict[str, Any],
        recipients: List[str],
        subject: str,
        text_body: str,
        html_body: Optional[str] = None,
        timeout: float = 12.0
    ):
        super().__init__()
        self.smtp_config = smtp_config
        self.recipients = recipients
        self.subject = subject
        self.text_body = text_body
        self.html_body = html_body
        self.timeout = timeout

    def run(self):
        """Runs the blocking SMTP network send on the background worker thread."""
        try:
            success, message = send_smtp_email(
                smtp_config=self.smtp_config,
                recipients=self.recipients,
                subject=self.subject,
                text_body=self.text_body,
                html_body=self.html_body,
                timeout=self.timeout
            )
            self.finished_signal.emit(success, message)
        except Exception as e:
            self.finished_signal.emit(False, f"Internal email worker error: {e}")


class AlertNotifier(QObject):
    """
    Coordinates desktop tray alerts and background email notifications.
    Maintains alert cooldown to prevent repetitive spam.
    """

    alert_emitted = Signal(str, str, str)  # (title, message, level: 'CRITICAL' | 'INFO')
    email_dispatched = Signal(bool, str)   # (success, status_msg)

    def __init__(self, parent_widget=None, cooldown_seconds: int = 300):
        super().__init__()
        self.parent_widget = parent_widget
        self.cooldown_seconds = cooldown_seconds
        self.last_alert_time: Dict[str, float] = {}
        self.active_workers: List[EmailWorker] = []
        self.tray_icon: Optional[QSystemTrayIcon] = None

        self._init_tray_icon()

    def _init_tray_icon(self):
        """Initializes system tray icon if supported on current platform."""
        try:
            if QSystemTrayIcon.isSystemTrayAvailable():
                app = QApplication.instance()
                icon = app.style().standardIcon(QStyle.SP_ComputerIcon) if app else None
                self.tray_icon = QSystemTrayIcon(self)
                if icon and not icon.isNull():
                    self.tray_icon.setIcon(icon)
                self.tray_icon.setToolTip("ServerMon - Infrastructure Monitor")
                self.tray_icon.show()
        except Exception as e:
            logging.warning(f"Could not initialize QSystemTrayIcon: {e}")
            self.tray_icon = None

    def show_desktop_alert(self, title: str, message: str, is_critical: bool = True):
        """Displays system tray notification balloon and logs event."""
        level = "CRITICAL" if is_critical else "INFO"
        self.alert_emitted.emit(title, message, level)

        if self.tray_icon and self.tray_icon.isVisible():
            try:
                icon_type = QSystemTrayIcon.Critical if is_critical else QSystemTrayIcon.Information
                self.tray_icon.showMessage(title, message, icon_type, 7000)
            except Exception as e:
                logging.warning(f"Failed to display tray message: {e}")

    def notify_server_down(
        self,
        target: dict,
        result: dict,
        smtp_config: Optional[Dict[str, Any]] = None,
        retries_done: int = 3
    ) -> bool:
        """
        Emits desktop notification and dispatches async alert email.
        Applies per-server cooldown to prevent notification storms.
        """
        target_id = target.get("id", "default")
        now = time.time()
        last_sent = self.last_alert_time.get(target_id, 0.0)

        name = target.get("name", "Unknown Server")
        host = target.get("host", "Unknown Host")
        err = result.get("error") or target.get("error") or "Unreachable"

        # Show desktop notification immediately
        title = f"Server Down: {name}"
        checks_word = "failed check" if retries_done == 1 else "failed checks"
        desc = f"Endpoint {host} is unreachable ({retries_done} {checks_word}).\nError: {err}"
        self.show_desktop_alert(title, desc, is_critical=True)

        # Check cooldown for email dispatch
        if (now - last_sent) < self.cooldown_seconds:
            logging.info(f"Notification cooldown active for server {name} ({target_id}); skipping email.")
            return False

        self.last_alert_time[target_id] = now

        if not smtp_config or not smtp_config.get("email_alerts_enabled"):
            return True

        recipients_raw = smtp_config.get("email_recipients", "")
        recipients = parse_recipients(recipients_raw)
        if not recipients:
            logging.warning(f"Email alerts enabled, but no valid recipients found in settings for {name}.")
            return False

        subject, text_body, html_body = format_down_alert(target, failure_count=retries_done, error_msg=err)
        self.send_async(smtp_config, recipients, subject, text_body, html_body)
        return True

    def notify_server_recovered(
        self,
        target: dict,
        result: dict,
        smtp_config: Optional[Dict[str, Any]] = None
    ) -> bool:
        """
        Emits desktop recovery notification and optionally dispatches recovery email.
        """
        name = target.get("name", "Unknown Server")
        host = target.get("host", "Unknown Host")

        title = f"Server Recovered: {name}"
        desc = f"Endpoint {host} is back ONLINE."
        self.show_desktop_alert(title, desc, is_critical=False)

        # Clear cooldown so next down event can fire cleanly
        target_id = target.get("id", "default")
        self.last_alert_time.pop(target_id, None)

        if not smtp_config or not smtp_config.get("email_alerts_enabled"):
            return True

        recipients = parse_recipients(smtp_config.get("email_recipients", ""))
        if not recipients:
            return False

        subject, text_body, html_body = format_recovery_alert(target)
        self.send_async(smtp_config, recipients, subject, text_body, html_body)
        return True

    def send_async(
        self,
        smtp_config: Dict[str, Any],
        recipients: List[str],
        subject: str,
        text_body: str,
        html_body: Optional[str] = None,
        callback=None
    ):
        """Launches background EmailWorker thread."""
        worker = EmailWorker(
            smtp_config=smtp_config,
            recipients=recipients,
            subject=subject,
            text_body=text_body,
            html_body=html_body
        )

        def _on_done(success: bool, msg: str, w=worker):
            self.email_dispatched.emit(success, msg)
            if callback:
                callback(success, msg)
            if w in self.active_workers:
                self.active_workers.remove(w)

        worker.finished_signal.connect(_on_done)
        self.active_workers.append(worker)
        worker.start()

    def stop_all(self, timeout_ms: int = 800):
        """Waits for active background email worker threads to conclude and hides tray icon."""
        for worker in list(self.active_workers):
            if worker.isRunning():
                worker.wait(timeout_ms)
        self.active_workers.clear()
        if self.tray_icon:
            try:
                self.tray_icon.hide()
            except Exception:
                pass

